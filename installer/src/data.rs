use anyhow::{Context, Result, bail};
use serde_json::{Map, Value, json};
use std::{fs, path::Path};

pub type Table = Map<String, Value>;
pub fn object(value: &Value) -> Result<&Table> {
    value.as_object().context("Expected a table/object")
}
pub fn object_mut(value: &mut Value) -> Result<&mut Table> {
    value.as_object_mut().context("Expected a table/object")
}
pub fn table(value: &Value, key: &str) -> Result<Table> {
    match value.get(key) {
        None => Ok(Table::new()),
        Some(value) => Ok(object(value)?.clone()),
    }
}
pub fn string<'a>(value: &'a Value, key: &str, default: &'a str) -> Result<&'a str> {
    match value.get(key) {
        None => Ok(default),
        Some(value) => value.as_str().with_context(|| format!("Expected a string for {key}")),
    }
}
pub fn strings(value: &Value) -> Result<Vec<String>> {
    match value {
        Value::Null => Ok(vec![]),
        Value::Array(values) => values.iter().map(|v| v.as_str().map(str::to_owned).context("Expected a string array")).collect(),
        _ => bail!("Expected a string array"),
    }
}
pub fn load_toml(path: &Path) -> Result<Value> {
    if !path.exists() { return Ok(json!({})); }
    parse_toml(&fs::read_to_string(path)?, &path.display().to_string())
}
pub fn parse_toml(text: &str, location: &str) -> Result<Value> {
    toml::from_str(text).with_context(|| format!("Invalid TOML in {location}"))
}
pub fn load_json(path: &Path) -> Result<Value> {
    if !path.exists() { return Ok(json!({})); }
    let value = serde_json::from_str(&fs::read_to_string(path)?)
        .with_context(|| format!("Invalid JSON in {}", path.display()))?;
    object(&value)?;
    Ok(value)
}
pub fn render_toml(value: &Value) -> Result<String> {
    let text = format!("# Generated by xerrion-dev-tooling; rerun with the complete tool selection.\n\n{}", toml::to_string_pretty(value)?);
    parse_toml(&text, "generated config")?;
    Ok(text)
}
pub fn shell_join(args: &[String]) -> Result<String> {
    shlex::try_join(args.iter().map(String::as_str)).context("Command contains a NUL character")
}
