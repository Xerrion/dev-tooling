def package_manager(directory: Path, project: Path) -> tuple[str, dict[str, Any], Path]:
    entries: list[tuple[Path, dict[str, Any]]] = []
    current = directory
    while True:
        path = inside(project, current.relative_to(project) / "package.json")
        data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
        if not isinstance(data, dict):
            raise TypeError(f"package.json must contain an object: {path}")
        entries.append((current, data))
        if current == project:
            break
        current = current.parent
    locks = [
        ("bun", "bun.lock"),
        ("bun", "bun.lockb"),
        ("pnpm", "pnpm-lock.yaml"),
        ("npm", "package-lock.json"),
        ("yarn", "yarn.lock"),
    ]
    manager, owner, request = "bun", directory, ""
    for location, data in entries:
        declaration = data.get("packageManager", "")
        if not isinstance(declaration, str):
            raise TypeError(f"packageManager must be a string: {location / 'package.json'}")
        if declaration:
            manager = declaration.partition("@")[0]
            if manager not in {"bun", "npm", "pnpm", "yarn"}:
                raise ValueError(f"Unsupported package manager: {declaration}")
            owner, request = location, declaration
            break
        found = next(
            (name for name, lock in locks if inside(project, location.relative_to(project) / lock).exists()), None
        )
        if found:
            manager, owner = found, location
            break
    child = copy.deepcopy(entries[0][1])
    if request and not child.get("packageManager"):
        child["packageManager"] = request
    child_has_package = (directory / "package.json").exists()
    for location, data in entries:
        workspace = (
            bool(data.get("workspaces"))
            or inside(project, location.relative_to(project) / "pnpm-workspace.yaml").exists()
        )
        matching_lock = any(
            inside(project, location.relative_to(project) / lock).exists() for name, lock in locks if name == manager
        )
        if (location == directory or workspace or not child_has_package) and (matching_lock or location == owner):
            owner = location
            break
    if child_has_package and owner != directory:
        owner_data = next(data for location, data in entries if location == owner)
        workspace = bool(owner_data.get("workspaces")) or (owner / "pnpm-workspace.yaml").exists()
        if not workspace:
            owner = directory
    return manager, child, owner


def manager_tools(profile: dict[str, Any], manager: str, package: dict[str, Any]) -> None:
    if manager != "bun":
        profile["tools"].pop("bun", None)
    if manager in {"pnpm", "yarn"}:
        profile["tools"][manager] = package.get("packageManager", "").partition("@")[2].split("+")[0] or "latest"


def delegation_cycle(action: str, alias: str, tasks: dict[str, Any]) -> bool:
    names = set(tasks) | {alias}
    visited: set[str] = set()

    def reaches_alias(name: str) -> bool:
        if name == alias:
            return True
        if name in visited:
            return False
        visited.add(name)
        task = tasks.get(name, {})
        if not isinstance(task, dict):
            return False
        dependencies = task.get("depends", []) + task.get("depends_post", [])
        for dependency in dependencies:
            pattern = dependency.get("task", "") if isinstance(dependency, dict) else dependency
            for match in names:
                if fnmatch.fnmatchcase(match, pattern) and reaches_alias(match):
                    return True
        return False

    return reaches_alias(action)


def js_tasks(profile: dict[str, Any], directory: Path, existing: dict[str, Any], plan: Plan) -> str:
    package = inside(plan.project, directory.relative_to(plan.project) / "package.json")
    manager, data, owner = package_manager(directory, plan.project)
    installs = {
        "bun": "bun install --frozen-lockfile"
        if any((owner / name).exists() for name in ("bun.lock", "bun.lockb"))
        else "bun install",
        "npm": "npm ci" if (owner / "package-lock.json").exists() else "npm install",
        "pnpm": "pnpm install --frozen-lockfile" if (owner / "pnpm-lock.yaml").exists() else "pnpm install",
        "yarn": "yarn install",
    }
    profile["tasks"]["deps:javascript"]["run"] = installs[manager]
    profile["tasks"]["deps:javascript"]["dir"] = owner.relative_to(plan.project).as_posix()
    profile["tasks"]["deps:javascript"]["description"] = f"Install JavaScript dependencies using {manager}"
    manager_tools(profile, manager, data)
    for action in ("typecheck", "test"):
        name = f"{action}:javascript"
        if name in existing["tasks"]:
            continue
        if action in data.get("scripts", {}):
            profile["tasks"][name]["run"] = f"{manager} run {action}"
        elif action in existing["tasks"]:
            graph = profile["tasks"] | existing["tasks"]
            if delegation_cycle(action, name, graph):
                profile["tasks"].pop(name)
                plan.notes.append(f"WARNING: omitted {name}: delegating to {action} would create a dependency cycle")
            else:
                profile["tasks"][name] = {
                    "description": f"Run the project's {action} task and prerequisites",
                    "depends": [action],
                }
        else:
            profile["tasks"].pop(name)
            plan.notes.append(f"WARNING: omitted {name}: no package script or existing project task named {action}")
    if not package.exists():
        plan.notes.append(
            "WARNING: JavaScript has no package.json; create the application package before installing dependencies"
        )
    return manager


def build_plan(args: argparse.Namespace) -> Plan:
    project = Path(args.project).expanduser().resolve()
    if not project.is_dir():
        raise ValueError(f"Project directory does not exist: {project}")
    plan = Plan(project)
    inside(project, BACKUPS)
    existing, mise_paths = existing_mise(project)
    tools = list(dict.fromkeys("javascript" if tool == "typescript" else tool for tool in args.tools))
    directories: dict[str, Path] = {}
    for tool in tools:
        relative = getattr(args, f"{tool}_dir")
        if relative is None:
            relative = existing["vars"].get(f"{tool}_dir", ".")
        directory = inside(project, relative)
        if not directory.is_dir():
            raise ValueError(f"Tool working directory does not exist: {directory}")
        directories[tool] = directory
    generated: dict[str, Any] = {"tools": {}, "vars": {}, "tasks": {}}
    selected_tasks: set[str] = set()
    scripts = False
    python_version = args.python_version or existing["vars"].get("python_version", "3.14")
    if "python" in tools:
        pyproject = load_toml(inside(project, directories["python"].relative_to(project) / "pyproject.toml"))
        is_project = "project" in pyproject or "workspace" in pyproject.get("tool", {}).get("uv", {})
        scripts = args.python_mode == "scripts" or (args.python_mode == "auto" and not is_project)
        if args.python_mode == "project" and not is_project:
            raise ValueError("Python project mode requires project or uv workspace metadata in pyproject.toml")
        minimum = re.search(
            r"(?:>=|==|~=)\s*(3\.\d+)",
            pyproject.get("project", {}).get("requires-python", ""),
        )
        if minimum and not args.python_version and "python_version" not in existing["vars"]:
            python_version = minimum.group(1)
    if not re.fullmatch(r"3\.\d+", python_version):
        raise ValueError("--python-version must be a major.minor version, such as 3.14")
    for tool in tools:
        profile = load_toml(TEMPLATES / "mise" / "profiles" / f"{tool}.toml")
        profile = copy.deepcopy(profile)
        profile.setdefault("tools", {})
        profile["vars"][f"{tool}_dir"] = directories[tool].relative_to(project).as_posix()
        if tool == "python":
            directory = directories[tool]
            inherited_files = shlex.split(existing["vars"].get("python_files", ""))
            files = (
                args.python_files
                or inherited_files
                or [name for name in ("src", "tests") if (directory / name).is_dir()]
                or ["."]
            )
            for name in files:
                inside(project, directory.relative_to(project) / name)
            profile["vars"]["python_files"] = shlex.join(files)
            profile["vars"]["python_version"] = python_version
            if args.python_executable:
                inside(project, directory.relative_to(project) / args.python_executable)
                profile["vars"]["python_executable"] = args.python_executable
            elif os.name == "nt":
                profile["vars"]["python_executable"] = ".venv/Scripts/python.exe"
            if scripts:
                profile["tasks"].pop("deps:python")
                profile["tasks"].pop("test:python")
                if not args.python_executable:
                    profile["tasks"]["typecheck:python"]["run"] = (
                        "ty check --python-version {{ vars.python_version | quote }} {{ vars.python_files }}"
                    )
                plan.notes.append("Python scripts mode: no uv project, dependency sync, or pytest task is created")
            elif "dev" not in pyproject.get("dependency-groups", {}):
                profile["tasks"]["deps:python"]["run"] = "uv sync --locked"
        if tool == "javascript":
            js_tasks(profile, directories[tool], existing, plan)
        if tool == "markdown":
            markdown_manager, markdown_package, markdown_owner = package_manager(directories[tool], project)
            manager_tools(profile, markdown_manager, markdown_package)
            prefix = {
                "bun": "bun run",
                "npm": "npm exec --no --",
                "pnpm": "pnpm exec",
                "yarn": "yarn exec",
            }[markdown_manager]
            for task in profile["tasks"].values():
                runs = task["run"]
                task["run"] = (
                    [run.replace("bun run", prefix, 1) for run in runs]
                    if isinstance(runs, list)
                    else runs.replace("bun run", prefix, 1)
                )
            if any(
                (directories[tool] / name).exists() for name in (".markdownlint-cli2.jsonc", ".markdownlint-cli2.yaml")
            ):
                plan.notes.append(
                    "WARNING: markdownlint-cli2 config is not used by markdownlint-cli; "
                    "review the separate .markdownlint.json rules"
                )
        for name, version in profile.get("tools", {}).items():
            if name in existing["tools"]:
                plan.notes.append(f"KEEP mise tool {name}: existing project version {existing['tools'][name]}")
                continue
            request = args.node_version if name == "node" and args.node_version else version
            if name in generated["tools"] and generated["tools"][name] != request:
                raise ValueError(
                    f"Conflicting {name} versions in selected profiles; pass --node-version for a shared Node version"
                )
            generated["tools"][name] = request
        for name, value in profile["vars"].items():
            if name in existing["vars"]:
                explicit = {
                    f"{tool}_dir": getattr(args, f"{tool}_dir"),
                    "python_files": args.python_files,
                    "python_version": args.python_version,
                    "python_executable": args.python_executable,
                }
                if explicit.get(name) is not None and existing["vars"][name] != value:
                    raise ValueError(
                        f"Existing mise variable {name} overrides this argument; update it in the project config first"
                    )
                plan.notes.append(f"KEEP mise variable {name}: existing project override")
                continue
            generated["vars"][name] = value
        for name, task in profile["tasks"].items():
            selected_tasks.add(name)
            if name in existing["tasks"]:
                plan.notes.append(f"KEEP mise task {name}: existing project definition takes precedence")
                continue
            generated["tasks"][name] = task
        add_configs(plan, tool, directories[tool], args.replace_configs, python_version, args.overwrite_rust_toolchain)
    plan.stage(FRAGMENT, render_toml(generated))
    available = generated["tasks"] | existing["tasks"]
    central = add_central(plan, available, existing, selected_tasks)
    for tool in tools:
        if tool in {"javascript", "markdown"}:
            ignore = directories[tool].relative_to(project) / ".gitignore"
            path = inside(project, ignore)
            if not path.exists():
                plan.stage(ignore, "node_modules/\ndist/\nbuild/\ncoverage/\n")
    ignore_path = inside(project, ".gitignore")
    ignore_change = plan.changes.get(Path(".gitignore"))
    ignore = (
        ignore_change.after.decode()
        if ignore_change and ignore_change.after is not None
        else (ignore_path.read_text(encoding="utf-8") if ignore_path.exists() else "")
    )
    if "/.tooling-backups/" not in ignore.splitlines():
        plan.stage(
            ".gitignore",
            ignore + ("\n" if ignore and not ignore.endswith("\n") else "") + "/.tooling-backups/\n",
        )
    agents_name = args.agents_file
    if agents_name is None:
        agents_name = "AGENTS.md"
    agents = inside(project, agents_name)
    before = agents.read_text(encoding="utf-8") if agents.exists() else ""
    block = agent_block(tools, directories, available | central, scripts, project)
    plan.stage(agents.relative_to(project), update_agents(before, block))
    if args.install_tools or args.install_deps:
        plan.notes.append(
            "Installation trusts project mise config. Hooks and package builds may execute project or "
            "third-party code; downloads can occur."
        )
        for path in dict.fromkeys([*mise_paths, project / central_filename(project), project / FRAGMENT]):
            plan.command(["mise", "trust", str(path)], project)
    if args.install_tools:
        plan.command(["mise", "install"], project)
        if "rust" in tools:
            directory = directories["rust"]
            path = existing_config(project, directory, "rust-toolchain", "rust-toolchain.toml")
            channel = "stable"
            toolchain: dict[str, Any] = {"components": ["clippy", "rustfmt"]}
            planned = plan.changes.get(directory.relative_to(project) / "rust-toolchain.toml")
            if planned and planned.after is not None:
                toolchain = tomllib.loads(planned.after.decode("utf-8"))["toolchain"]
                channel = toolchain.get("channel", "stable")
            elif path:
                text = path.read_text(encoding="utf-8").strip()
                if path.suffix == ".toml" or text.startswith("["):
                    toolchain = tomllib.loads(text).get("toolchain", {})
                    channel = toolchain.get("channel", "stable")
                else:
                    channel = text
            command = [
                "rustup",
                "toolchain",
                "install",
                channel,
                "--profile",
                toolchain.get("profile", "minimal"),
            ]
            for component in dict.fromkeys([*toolchain.get("components", []), "clippy", "rustfmt"]):
                command += ["--component", component]
            for target in toolchain.get("targets", []):
                command += ["--target", target]
            plan.command(command, directory)
    if args.install_deps:
        if "python" in tools and not scripts:
            directory = directories["python"]
            data = load_toml(directory / "pyproject.toml")
            dev = data.get("dependency-groups", {}).get("dev", [])
            pytest_present = any(
                isinstance(item, str) and re.match(r"pytest(?:\s|[<>=!~;\[]|$)", item, re.IGNORECASE)
                for item in [*dev, *data.get("project", {}).get("dependencies", [])]
            )
            if not pytest_present:
                plan.command(["mise", "exec", "--", "uv", "add", "--dev", "pytest"], directory)
            command = ["mise", "exec", "--", "uv", "sync"]
            if (directory / "uv.lock").exists() or not pytest_present:
                command.append("--locked")
            if dev or not pytest_present:
                command += ["--group", "dev"]
            plan.command(command, directory)
        if "javascript" in tools:
            plan.command(["mise", "run", "deps:javascript"], project)
        if "markdown" in tools:
            directory = directories["markdown"]
            package = inside(project, directory.relative_to(project) / "package.json")
            if not package.exists():
                directory = markdown_owner
                package = inside(project, directory.relative_to(project) / "package.json")
            if not package.exists():
                plan.stage(
                    package.relative_to(project),
                    json.dumps({"private": True}, indent=2) + "\n",
                )
            add = {
                "bun": ["bun", "add", "--dev", "--exact"],
                "npm": ["npm", "install", "--save-dev", "--save-exact"],
                "pnpm": ["pnpm", "add", "--save-dev", "--save-exact"],
                "yarn": ["yarn", "add", "--dev", "--exact"],
            }[markdown_manager]
            plan.command(["mise", "exec", "--", *add, "markdownlint-cli", "prettier"], directory)
        backup_directories: set[Path] = set()
        for tool in tools:
            current = directories[tool]
            while True:
                backup_directories.add(current)
                if current == project:
                    break
                current = current.parent
        for directory in backup_directories:
            for filename in (
                "pyproject.toml",
                "uv.lock",
                "package.json",
                "bun.lock",
                "package-lock.json",
                "pnpm-lock.yaml",
                "yarn.lock",
            ):
                path = inside(project, directory.relative_to(project) / filename)
                if path.exists() and path.is_file():
                    plan.dependency_backups[path.relative_to(project)] = path.read_bytes()
    plan.notes.append(
        "Root/local mise files, parent configs, selected environments, and custom discovery settings can "
        "override this fragment. Verify with mise config and mise tasks ls."
    )
    return plan


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description=__doc__)
    result.add_argument(
        "project",
        help="Existing project directory (not modified unless --apply is set)",
    )
    result.add_argument("--tools", nargs="+", required=True, choices=[*CONFIGS, "typescript"])
    mode = result.add_mutually_exclusive_group()
    mode.add_argument(
        "--apply",
        action="store_true",
        help="Write the displayed changes and run explicitly requested install commands",
    )
    mode.add_argument("--dry-run", action="store_true", help="Preview only (the default)")
    for tool in CONFIGS:
        result.add_argument(
            f"--{tool}-dir",
            help=f"Project-relative {tool} working directory; defaults to an existing mise variable or '.'",
        )
    result.add_argument(
        "--python-files",
        nargs="+",
        help="Paths relative to --python-dir; defaults to existing src/tests directories, otherwise '.'",
    )
    result.add_argument(
        "--python-version",
        help="Minimum Python target version, e.g. 3.14; inferred from requires-python when available",
    )
    result.add_argument("--python-executable", help="Project interpreter path relative to --python-dir")
    result.add_argument("--python-mode", choices=["auto", "project", "scripts"], default="auto")
    result.add_argument(
        "--node-version",
        help="Resolve conflicting Node requests when combining JavaScript and Markdown",
    )
    result.add_argument(
        "--agents-file",
        help="Project-relative instructions file; defaults to existing AGENTS.md",
    )
    result.add_argument(
        "--overwrite",
        "--replace-configs",
        dest="replace_configs",
        action="store_true",
        help="Back up and replace selected tool configs, removing obsolete alternatives; "
        "Rust toolchain pins stay protected",
    )
    result.add_argument(
        "--overwrite-rust-toolchain",
        action="store_true",
        help="Explicitly allow replacing an existing Rust compiler/toolchain pin with the template",
    )
    result.add_argument(
        "--install-tools",
        action="store_true",
        help="Plan mise installation and selected Rust toolchain installation; --apply executes them",
    )
    result.add_argument(
        "--install-deps",
        action="store_true",
        help="Plan project/test/Markdown dependency installation; "
        "--apply executes it and can update manifests/lockfiles",
    )
    return result


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    try:
        plan = build_plan(args)
        report(f"{'APPLY' if args.apply else 'PREVIEW (no writes or installs)'}: {plan.project}")
        for note in dict.fromkeys(plan.notes):
            report(note)
        for change in plan.changes.values():
            action = "REMOVE" if change.after is None else ("CREATE" if change.before is None else "UPDATE")
            report(f"{action} {change.relative}")
        for command in plan.commands:
            report(f"PLAN RUN [{command.directory.relative_to(plan.project)}] {shlex.join(command.argv)}")
        if args.apply:
            plan.apply()
            report(f"Applied {len(plan.changes)} file changes.")
        else:
            report("Rerun with --apply to perform this plan. No installation commands run without --apply.")
        return 0
    except (ValueError, TypeError, OSError, subprocess.CalledProcessError) as error:
        report(f"Error: {error}", error=True)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
