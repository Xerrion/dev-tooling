def report(message: str, *, error: bool = False) -> None:
    # Stream writes keep CLI reporting intact under the template's no-print rule.
    stream = sys.stderr if error else sys.stdout
    stream.write(message + "\n")
    stream.flush()


def inside(root: Path, relative: str | Path) -> Path:
    """Do not follow links, including links in existing parent directories."""
    relative = Path(relative)
    if relative.is_absolute() or ".." in relative.parts:
        raise ValueError(f"Expected a project-relative path without '..': {relative}")
    path = root
    for part in relative.parts:
        path /= part
        if path.is_symlink():
            raise ValueError(f"Refusing symlinked path: {path}")
    if not path.resolve().is_relative_to(root):
        raise ValueError(f"Path escapes the project: {relative}")
    return path


def load_toml(path: Path) -> dict[str, Any]:
    return tomllib.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def toml_value(value: object) -> str:
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    raise TypeError(f"Unsupported generated TOML value: {value!r}")


def render_toml(data: dict[str, Any], *, include_parent_tables: bool = True) -> str:
    lines = ["# Generated by install.py; rerun with the complete tool selection."]

    def table(values: dict[str, Any], keys: tuple[str, ...] = ()) -> None:
        if keys and (include_parent_tables or any(not isinstance(value, dict) for value in values.values())):
            lines.extend(["", "[" + ".".join(json.dumps(key) for key in keys) + "]"])
        for key, value in values.items():
            if not isinstance(value, dict):
                lines.append(f"{json.dumps(key)} = {toml_value(value)}")
        for key, value in values.items():
            if isinstance(value, dict):
                table(value, (*keys, key))

    table(data)
    result = "\n".join(lines) + "\n"
    tomllib.loads(result)
    return result


@dataclass
class Change:
    relative: Path
    before: bytes | None
    after: bytes | None


@dataclass
class Command:
    argv: list[str]
    directory: Path


@dataclass
class Plan:
    project: Path
    changes: dict[Path, Change] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)
    commands: list[Command] = field(default_factory=list)
    dependency_backups: dict[Path, bytes] = field(default_factory=dict)

    def stage(self, relative: str | Path, text: str) -> None:
        relative = Path(relative)
        path = inside(self.project, relative)
        if path.exists() and not path.is_file():
            raise ValueError(f"Expected a file: {path}")
        before = path.read_bytes() if path.exists() else None
        after = text.encode("utf-8")
        if before != after:
            self.changes[relative] = Change(relative, before, after)

    def remove(self, relative: Path) -> None:
        path = inside(self.project, relative)
        if path.exists():
            if not path.is_file():
                raise ValueError(f"Expected a file: {path}")
            self.changes[relative] = Change(relative, path.read_bytes(), None)

    def command(self, argv: list[str], directory: Path) -> None:
        self.commands.append(Command(argv, directory))

    def apply(self) -> None:
        backup_root = inside(self.project, BACKUPS)
        if backup_root.exists() and not backup_root.is_dir():
            raise ValueError(f"Expected a backup directory: {backup_root}")
        # Detect edits made since planning before writing the first file.
        for change in self.changes.values():
            path = inside(self.project, change.relative)
            current = path.read_bytes() if path.exists() else None
            if current != change.before:
                raise ValueError(f"File changed during planning; rerun: {path}")
        for relative, before in self.dependency_backups.items():
            if inside(self.project, relative).read_bytes() != before:
                raise ValueError(f"Dependency file changed during planning; rerun: {relative}")
        existing = {change.relative for change in self.changes.values() if change.before is not None}
        existing.update(self.dependency_backups)
        if existing:
            stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ") + "-" + uuid.uuid4().hex[:8]
            backup = backup_root / stamp
            for relative in sorted(existing):
                destination = backup / relative
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(inside(self.project, relative), destination)
            report(f"Backups: {backup}")
        for change in self.changes.values():
            path = inside(self.project, change.relative)
            if change.after is None:
                path.unlink()
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            mode = stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o644
            with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as temporary:
                temporary_path = Path(temporary.name)
                temporary.write(change.after)
            try:
                temporary_path.chmod(mode)
                temporary_path.replace(path)
            finally:
                temporary_path.unlink(missing_ok=True)
        for command in self.commands:
            subprocess.run(command.argv, cwd=command.directory, check=True)


def central_filename(project: Path) -> str:
    return ".mise.toml" if inside(project, ".mise.toml").exists() else "mise.toml"


def existing_mise(project: Path) -> tuple[dict[str, Any], list[Path]]:
    """Read project-level config without evaluating templates, hooks, or includes."""
    merged: dict[str, Any] = {"tools": {}, "vars": {}, "tasks": {}}
    paths: list[Path] = []
    candidates: list[Path] = []
    for base in (".config/mise", ".mise", "mise"):
        fragments = inside(project, Path(base) / "conf.d")
        if fragments.exists():
            candidates.extend(sorted(path for path in fragments.glob("*.toml") if not path.name.startswith(".")))
            for folder in sorted(fragments.iterdir()):
                if folder.is_dir() and not folder.name.startswith("."):
                    candidates.extend(folder / name for name in ("mise.toml", "mise.local.toml"))
        candidates.append(project / base / "config.toml")
        if base == ".config/mise":
            candidates.extend([project / base / "mise.toml", project / ".config/mise.toml"])
    candidates.extend(project / name for name in ("mise.toml", ".mise.toml"))
    candidates.extend(
        project / name
        for name in (
            ".config/mise/config.local.toml",
            ".config/mise.local.toml",
            ".mise/config.local.toml",
            "mise/config.local.toml",
            "mise.local.toml",
            ".mise.local.toml",
        )
    )
    for candidate in candidates:
        if candidate.relative_to(project) == FRAGMENT:
            continue
        path = inside(project, candidate.relative_to(project))
        if path.exists():
            text = path.read_text(encoding="utf-8")
            data = tomllib.loads(text)
            if path.parent == project and path.name in {"mise.toml", ".mise.toml"}:
                text = update_managed(text, "", AGGREGATE_START, AGGREGATE_END)
                data = tomllib.loads(text)
            paths.append(path)
            for section, values in merged.items():
                values.update(data.get(section, {}))
    return merged, paths


def existing_config(project: Path, directory: Path, kind: str, filename: str) -> Path | None:
    current = directory
    while True:
        names = ALTERNATIVES.get(kind, [filename])
        for name in names:
            path = inside(project, current.relative_to(project) / name)
            if path.exists():
                return path
        pyproject = inside(project, current.relative_to(project) / "pyproject.toml")
        if kind in {"ruff", "ty"} and kind in load_toml(pyproject).get("tool", {}):
            return pyproject
        package = inside(project, current.relative_to(project) / "package.json")
        if kind == "prettier" and package.exists() and "prettier" in json.loads(package.read_text(encoding="utf-8")):
            return package
        if current == project:
            return None
        current = current.parent


def add_configs(
    plan: Plan, tool: str, directory: Path, replace: bool, version: str, overwrite_toolchain: bool = False
) -> None:
    for source, kind in CONFIGS[tool]:
        template = TEMPLATES / source
        destination = directory / template.name
        inside(plan.project, destination.relative_to(plan.project))
        found = existing_config(plan.project, directory, kind, template.name)
        should_replace = overwrite_toolchain if kind == "rust-toolchain" else replace
        if found and not should_replace:
            plan.notes.append(f"KEEP {found.relative_to(plan.project)}: existing {kind} configuration")
            continue
        if should_replace:
            for name in ALTERNATIVES.get(kind, []):
                alternate = inside(plan.project, directory.relative_to(plan.project) / name)
                if alternate != destination:
                    plan.remove(alternate.relative_to(plan.project))
            if kind == "prettier":
                package = inside(plan.project, directory.relative_to(plan.project) / "package.json")
                if package.exists():
                    original = package.read_text(encoding="utf-8")
                    data = json.loads(original)
                    if "prettier" in data:
                        del data["prettier"]
                        indent = "\t" if "\n\t" in original else 2
                        plan.stage(
                            package.relative_to(plan.project),
                            json.dumps(data, indent=indent, ensure_ascii=False) + "\n",
                        )
        if found and found != destination:
            plan.notes.append(
                f"WARNING: {destination.relative_to(plan.project)} will override {kind} settings in "
                f"{found.relative_to(plan.project)}"
            )
        text = template.read_text(encoding="utf-8")
        if tool == "python":
            setting = "target-version" if kind == "ruff" else "python-version"
            target = "py" + version.replace(".", "") if kind == "ruff" else version
            text = re.sub(rf'(?m)^{setting}\s*=\s*"[^"]*"', f'{setting} = "{target}"', text)
        plan.stage(destination.relative_to(plan.project), text)


def update_managed(text: str, block: str, start_marker: str, end_marker: str) -> str:
    if text.count(start_marker) != text.count(end_marker) or text.count(start_marker) > 1:
        raise ValueError("Malformed or duplicate managed tooling markers")
    if start_marker in text:
        start, end = text.index(start_marker), text.index(end_marker)
        if end < start:
            raise ValueError("Reversed managed tooling markers")
        return text[:start] + block + text[end + len(end_marker) :]
    if not block:
        return text
    separator = "\n" if text.endswith("\n") else "\n\n"
    return text + (separator if text else "") + block + "\n"


def update_agents(text: str, block: str) -> str:
    return update_managed(text, block, START, END)


def add_central(plan: Plan, available: dict[str, Any], existing: dict[str, Any], selected: set[str]) -> dict[str, Any]:
    template = load_toml(TEMPLATES / "mise" / "mise.toml")
    tasks: dict[str, Any] = {}
    for name, original in template["tasks"].items():
        if name in existing["tasks"]:
            plan.notes.append(f"KEEP mise task {name}: existing project aggregate")
            continue
        task = copy.deepcopy(original)
        task["depends"] = [
            dependency for dependency in task["depends"] if dependency in available and dependency in selected
        ]
        if task["depends"]:
            tasks[name] = task
    graph = available | tasks
    for name, task in list(tasks.items()):
        if any(delegation_cycle(dependency, name, graph) for dependency in task["depends"]):
            plan.notes.append(f"WARNING: omitted {name}: aggregate would introduce a dependency cycle")
            del tasks[name]
            del graph[name]
    path = inside(plan.project, central_filename(plan.project))
    for name in ("mise.toml", ".mise.toml"):
        other = inside(plan.project, name)
        if other != path and other.exists():
            text = other.read_text(encoding="utf-8")
            if AGGREGATE_START in text:
                plan.stage(name, update_managed(text, "", AGGREGATE_START, AGGREGATE_END))
    before = path.read_text(encoding="utf-8") if path.exists() else ""
    block = AGGREGATE_START + "\n" + render_toml({"tasks": tasks}, include_parent_tables=False) + AGGREGATE_END
    after = update_managed(before, block, AGGREGATE_START, AGGREGATE_END)
    tomllib.loads(after)
    plan.stage(path.relative_to(plan.project), after)
    return tasks


